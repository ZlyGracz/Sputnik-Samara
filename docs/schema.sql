BEGIN;

CREATE TABLE alembic_version (
    version_num VARCHAR(32) NOT NULL, 
    CONSTRAINT alembic_version_pkc PRIMARY KEY (version_num)
);

-- Running upgrade  -> 0001

CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    email VARCHAR(255) NOT NULL, 
    password_hash VARCHAR(255) NOT NULL, 
    full_name VARCHAR(120) NOT NULL, 
    role VARCHAR(20) DEFAULT 'user' NOT NULL, 
    is_active BOOLEAN DEFAULT true NOT NULL, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    CONSTRAINT pk_users PRIMARY KEY (id), 
    CONSTRAINT ck_users_role_valid CHECK (role IN ('user', 'creator', 'admin'))
);

CREATE INDEX ix_users_email_trgm ON users USING gin (email gin_trgm_ops);

CREATE INDEX ix_users_full_name_trgm ON users USING gin (full_name gin_trgm_ops);

CREATE INDEX ix_users_role ON users (role);

CREATE UNIQUE INDEX uq_users_email_lower ON users (lower(email));

CREATE TABLE media (
    id UUID DEFAULT gen_random_uuid() NOT NULL, 
    kind VARCHAR(10) NOT NULL, 
    content_type VARCHAR(100) NOT NULL, 
    size_bytes INTEGER NOT NULL, 
    storage_path VARCHAR(500) NOT NULL, 
    uploaded_by BIGINT, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    CONSTRAINT pk_media PRIMARY KEY (id), 
    CONSTRAINT ck_media_kind_valid CHECK (kind IN ('image', 'audio')), 
    CONSTRAINT ck_media_size_positive CHECK (size_bytes > 0), 
    CONSTRAINT fk_media_uploaded_by_users FOREIGN KEY(uploaded_by) REFERENCES users (id) ON DELETE SET NULL, 
    CONSTRAINT uq_media_storage_path UNIQUE (storage_path)
);

CREATE TABLE courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    author_id BIGINT NOT NULL, 
    title VARCHAR(200) NOT NULL, 
    description TEXT DEFAULT '' NOT NULL, 
    cover_media_id UUID, 
    is_published BOOLEAN DEFAULT false NOT NULL, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    CONSTRAINT pk_courses PRIMARY KEY (id), 
    CONSTRAINT fk_courses_author_id_users FOREIGN KEY(author_id) REFERENCES users (id) ON DELETE RESTRICT, 
    CONSTRAINT fk_courses_cover_media_id_media FOREIGN KEY(cover_media_id) REFERENCES media (id) ON DELETE SET NULL
);

CREATE INDEX ix_courses_author_id ON courses (author_id);

CREATE INDEX ix_courses_description_trgm ON courses USING gin (description gin_trgm_ops);

CREATE INDEX ix_courses_published_created ON courses (created_at) WHERE is_published;

CREATE INDEX ix_courses_title_trgm ON courses USING gin (title gin_trgm_ops);

CREATE TABLE attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    user_id BIGINT NOT NULL, 
    course_id BIGINT NOT NULL, 
    status VARCHAR(20) DEFAULT 'in_progress' NOT NULL, 
    started_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    finished_at TIMESTAMP WITH TIME ZONE, 
    total_questions INTEGER NOT NULL, 
    score INTEGER, 
    CONSTRAINT pk_attempts PRIMARY KEY (id), 
    CONSTRAINT ck_attempts_finished_consistent CHECK ((status = 'in_progress' AND finished_at IS NULL AND score IS NULL) OR (status = 'finished' AND finished_at IS NOT NULL AND score IS NOT NULL)), 
    CONSTRAINT ck_attempts_status_valid CHECK (status IN ('in_progress', 'finished')), 
    CONSTRAINT ck_attempts_score_range CHECK (score IS NULL OR (score >= 0 AND score <= total_questions)), 
    CONSTRAINT ck_attempts_total_positive CHECK (total_questions >= 1), 
    CONSTRAINT fk_attempts_course_id_courses FOREIGN KEY(course_id) REFERENCES courses (id) ON DELETE CASCADE, 
    CONSTRAINT fk_attempts_user_id_users FOREIGN KEY(user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX ix_attempts_course_id ON attempts (course_id);

CREATE INDEX ix_attempts_user_started ON attempts (user_id, started_at DESC);

CREATE TABLE questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    course_id BIGINT NOT NULL, 
    position INTEGER NOT NULL, 
    text VARCHAR(1000) NOT NULL, 
    image_media_id UUID, 
    audio_media_id UUID, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    CONSTRAINT pk_questions PRIMARY KEY (id), 
    CONSTRAINT ck_questions_position_positive CHECK (position >= 1), 
    CONSTRAINT fk_questions_audio_media_id_media FOREIGN KEY(audio_media_id) REFERENCES media (id) ON DELETE SET NULL, 
    CONSTRAINT fk_questions_course_id_courses FOREIGN KEY(course_id) REFERENCES courses (id) ON DELETE CASCADE, 
    CONSTRAINT fk_questions_image_media_id_media FOREIGN KEY(image_media_id) REFERENCES media (id) ON DELETE SET NULL, 
    CONSTRAINT uq_questions_course_position UNIQUE (course_id, position) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE answer_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    question_id BIGINT NOT NULL, 
    position SMALLINT NOT NULL, 
    text VARCHAR(300) NOT NULL, 
    is_correct BOOLEAN DEFAULT false NOT NULL, 
    CONSTRAINT pk_answer_options PRIMARY KEY (id), 
    CONSTRAINT ck_answer_options_position_range CHECK (position BETWEEN 1 AND 4), 
    CONSTRAINT fk_answer_options_question_id_questions FOREIGN KEY(question_id) REFERENCES questions (id) ON DELETE CASCADE, 
    CONSTRAINT uq_answer_options_id_question UNIQUE (id, question_id), 
    CONSTRAINT uq_answer_options_question_position UNIQUE (question_id, position)
);

CREATE UNIQUE INDEX uq_answer_options_one_correct ON answer_options (question_id) WHERE is_correct;

CREATE TABLE attempt_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    attempt_id BIGINT NOT NULL, 
    question_id BIGINT NOT NULL, 
    option_id BIGINT NOT NULL, 
    answered_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    CONSTRAINT pk_attempt_answers PRIMARY KEY (id), 
    CONSTRAINT fk_attempt_answers_attempt_id_attempts FOREIGN KEY(attempt_id) REFERENCES attempts (id) ON DELETE CASCADE, 
    CONSTRAINT fk_attempt_answers_option_question FOREIGN KEY(option_id, question_id) REFERENCES answer_options (id, question_id) ON DELETE CASCADE, 
    CONSTRAINT fk_attempt_answers_question_id_questions FOREIGN KEY(question_id) REFERENCES questions (id) ON DELETE CASCADE, 
    CONSTRAINT uq_attempt_answers_attempt_question UNIQUE (attempt_id, question_id)
);

CREATE INDEX ix_attempt_answers_question_id ON attempt_answers (question_id);

INSERT INTO alembic_version (version_num) VALUES ('0001') RETURNING alembic_version.version_num;

COMMIT;

